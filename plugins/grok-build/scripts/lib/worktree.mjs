  "__pypackages__/",
  "*.egg-info/",
  "node_modules/",
  "target/",
  "obj/",
  ".gradle/",
  "*.tsbuildinfo",
  // Godot: .import is Godot 3's asset import CACHE DIRECTORY; .godot is Godot
  // 4's. Neither is source - both are regenerated from project assets.
  //
  // These are DIRECTORY patterns on purpose. Never "harmonize" `.import/` into
  // `*.import`, and never add `*.uid`: `icon.png.import` and `player.gd.uid`
  // are SOURCE. They carry the `uid://...` identifier that every `.tscn`/
  // `.tres` `ext_resource uid=` line resolves through, so dropping them from a
